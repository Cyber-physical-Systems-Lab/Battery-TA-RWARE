"""Assemble experiments/orders/README.md from the campaign outputs in experiments/orders/results/.

    python experiments/orders/make_results.py
"""
import csv
import os
import subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
NOTES = """## Reading these results

- **Confirmatory outcome: 7 of 9 pre-registered hypotheses supported.** NSP beats FIFO on throughput and
  lead time at the base load, with heavier coalitions and with tight batteries (H1, H2, H5, H6), and
  beats PLB (H4). LWF is slower than FIFO (H8). NSP and FIFO are equivalent when demand-limited (H9).
- **H3 (PLB > FIFO) is not supported.** On one of the 20 fresh seeds (1017) PLB drove the fleet into a
  model 2.1 hold-and-wait gridlock and completed no order after warm-up (reproduce:
  `python experiments/checks/known_gridlock.py`). *Post hoc only, not a confirmatory result:* without
  that seed PLB − FIFO = +2.5 orders/1000 ticks (95% CI [+1.1, +3.9]; 13 of 19 seeds better). The
  gridlock occurred twice in 1480 evaluation runs, both under PLB (also exploratory rate=0.05,
  seed 6), and never in the 1300 runs of the other nine rules, so it appears specific to PLB in this
  model; two events are too few to estimate its rate.
- **H7 (WSP type weights vs the equal-type ablation) is not supported**: −14 ticks, CI includes 0, so
  these data cannot attribute WSP's lead-time gain over FIFO to favouring outbound orders.
- **Where rules matter.** Differences appear only where capacity binds (base and higher load, larger
  coalitions, heterogeneous fleet, tight batteries, wider layout). With light packages or low demand
  the rules are indistinguishable. At base, NSP shortens travel (distance per delivery 49.3 -> 41.8
  cells), energy per order (-1.0 Wh) and the backlog (unfinished 35 -> 15), and its coalitions form
  faster (-1.8 ticks). Its coalition waiting ratio is nevertheless higher (0.20 -> 0.28): the ratio
  divides partner waiting by all committed robot-ticks, mostly travel, which NSP reduces; read the
  ratio together with formation time.
- **Scope.** All configurations use the basic warehouse family and the shared greedy charging rule; the
  rules schedule tasks and crews, not charging. Rejected orders (no stored package at arrival) are
  part of the outcome and differ by rule because inbound speed differs.

"""
RULES = ["nsp", "plb", "spt", "wsp", "wsp_eq", "zlp_2d", "edd", "cr", "lwf"]


def read(p):
    with open(p) as f:
        return list(csv.DictReader(f))


def effect_grid(paired, metric):
    cfgs = list(dict.fromkeys(p["config"] for p in paired))
    out = "| config | " + " | ".join(RULES) + " |\n|---|" + "---|" * len(RULES) + "\n"
    for c in cfgs:
        cells = []
        for r in RULES:
            q = [p for p in paired if p["config"] == c and p["rule"] == r and p["metric"] == metric]
            if not q:
                cells.append("–")
                continue
            q = q[0]
            v = "%+.3g" % float(q["diff"])
            cells.append("**%s**" % v if q["excludes_zero"] == "True" else v)
        out += "| %s | %s |\n" % (c, " | ".join(cells))
    return out


def main():
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=HERE).stdout.strip()
    runs = read(os.path.join(R, "exploratory", "runs.csv"))
    paired = read(os.path.join(R, "exploratory", "paired.csv"))
    errors = [r for r in runs if r["error"]]
    stalled = [r for r in runs if not r["error"] and float(r["stalls"] or 0) > 0]
    base_fifo = [r for r in runs if r["config"] == "base" and r["rule"] == "fifo"]
    with open(os.path.join(HERE, "README.md"), "w") as f:
        f.write("# Order-scheduling results\n\nGenerated by `python experiments/orders/make_results.py` "
                "(code at %s). Raw outputs (git-ignored): `experiments/orders/results/`.\n\n" % commit)
        f.write("## Reproduce\n\n```bash\npython experiments/orders/exploratory.py --seeds 10 --jobs 30   # ~15 min on 32 cores\n"
                "python experiments/orders/confirmatory.py --jobs 30              # protocol committed in 76193bd\n"
                "python experiments/orders/scalability.py --seeds 3 --ticks 1500 --jobs 30\n"
                "python experiments/orders/make_results.py\n```\n\n")
        f.write("Scenario factors: `experiments/orders/factors.py` (basic warehouse, 6 AGVs + 3 picking robots, "
                "3000 ticks, warmup 300). Every rule runs on the same seeds; differences are paired by seed "
                "(identical arrivals, inventory and robot placement), with percentile-bootstrap CIs.\n\n")
        f.write(NOTES)
        f.write("## Confirmatory (pre-registered, fresh seeds 1000-1019)\n\n")
        f.write(open(os.path.join(R, "confirmatory", "summary.md")).read().split("\n", 2)[2] + "\n")
        f.write("## Exploratory (seeds 0-9; no hypotheses fixed in advance)\n\n%d runs, %d errors; %d runs with a "
                "suspected stall%s.\n\n" % (len(runs), len(errors), len(stalled),
                                            (" (" + ", ".join("%s/%s/seed %s" % (r["config"], r["rule"], r["seed"])
                                                              for r in stalled) + ")") if stalled else ""))
        for m, title in (("throughput", "Throughput (orders per 1000 ticks)"), ("lead_time_mean", "Mean order lead time (ticks)"),
                         ("on_time_rate", "On-time completion rate"), ("energy_wh_per_order", "Energy per completed order (Wh)"),
                         ("coalition_waiting_ratio", "Coalition waiting ratio")):
            f.write("### %s: paired difference to FIFO (bold: 95%% CI excludes 0)\n\n" % title)
            f.write(effect_grid(paired, m) + "\n")
        f.write("FIFO levels at base (mean over seeds): throughput %.1f, lead time %.0f ticks, on-time %.2f, "
                "unfinished %.1f.\n\nFull per-config tables with means and CIs: `results/exploratory/summary.md`.\n\n"
                % tuple(sum(float(r[k]) for r in base_fifo) / len(base_fifo)
                        for k in ("throughput", "lead_time_mean", "on_time_rate", "unfinished")))
        f.write("### Where task time goes (base, mean share of open-task ticks by cause)\n\n| rule | " +
                " | ".join(["sequencing", "coalition_unavailable", "coalition_waiting", "congestion", "travel", "execution",
                            "blocked_inventory"]) + " |\n|---|" + "---|" * 7 + "\n")
        for rule in ["fifo"] + RULES:
            rs = [r for r in runs if r["config"] == "base" and r["rule"] == rule and not r["error"]]
            f.write("| %s | %s |\n" % (rule, " | ".join(
                "%.2f" % (sum(float(r["cause_" + k]) for r in rs) / len(rs))
                for k in ["sequencing", "coalition_unavailable", "coalition_waiting", "congestion", "travel", "execution",
                          "blocked_inventory"])))
        f.write("\n## Scalability\n\n")
        f.write(open(os.path.join(R, "scalability", "summary.md")).read().split("\n", 2)[2] + "\n")
    print(os.path.join(HERE, "README.md"))


if __name__ == "__main__":
    main()
